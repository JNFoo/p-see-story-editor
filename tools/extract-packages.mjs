const HEADER = (name, files) => `/* ${name}: GENERATED by tools/extract-packages.mjs from ${files.join(' and ')}.
   Do not edit this file; edit the editor sources and run \`npm run build\`. (A check in \`npm test\` fails if this file is out of date.)
   Copyright (c) 2026 LFC Foundry. MIT License, see LICENSE in the repository root. */
`;

/* The data an exported game is made from (the rules and player as minified text, plus the stylesheet), built exactly as editor/build-game.mjs does. */
function gameParts() {
  const here = at('editor/');
  const ctx = createContext({});
  runInContext(
    `${readFileSync(here + 'core.js', 'utf8')}\n${readFileSync(here + 'player.js', 'utf8')}
     this.order = KL_FEATURE_ORDER;
     this.head = 'const KL_FEATS={};\\n' + KL_RULES.map(n => eval(n)).concat(klPlayer).map(f => f.toString()).join('\\n');
     this.feats = {};
     KL_FEATURE_ORDER.forEach(n => { const f = eval('klFeat' + n[0].toUpperCase() + n.slice(1)); this.feats[n] = f.toString() + '\\nKL_FEATS.' + n + '=' + f.name + ';'; });`,
    ctx
  );
  const mini = code => transformSync(code, { minify: true, target: 'es2020', legalComments: 'none' }).code.trim();
  const js = { head: mini(ctx.head), feats: {} };
  ctx.order.forEach(n => (js.feats[n] = mini(ctx.feats[n])));
  const css = {};
  const chunks = { base: [] };
  let part = 'base';
  readFileSync(here + 'game.css', 'utf8')
    .split('\n')
    .forEach(line => {
      const m = /^\/\*@part (\w+)\*\/$/.exec(line.trim());
      if (m) (part = m[1]), (chunks[part] = chunks[part] || []);
      else chunks[part].push(line);
    });
  Object.keys(chunks).forEach(k => (css[k] = transformSync(chunks[k].join('\n'), { loader: 'css', minify: true, target: ['chrome100', 'safari15', 'firefox100'] }).code.trim()));
  return { js, css };
}

function bundle(entry, format, globalName, minify = false) {
  const r = buildSync({
    absWorkingDir: OUT,
    entryPoints: [entry],
    bundle: true,
    write: false,
    format,
    globalName,
    target: 'es2020',
    legalComments: 'inline',
    minify,
    charset: 'utf8'
  });
  return r.outputFiles[0].text;
}

export function generate() {
  for (const [name, def] of Object.entries(PACKAGES)) {
    const srcDir = at(`packages/${name}/src`);
    if (CHECK && existsSync(srcDir)) cpSync(srcDir, join(OUT, `packages/${name}/src`), { recursive: true });
    const all = load(def.files.map(f => at(f)));
    const cut = closure(all, def.roots);
    const body = cut.map(p => p.text).join('\n\n');
    const exported = [...new Set(def.roots)];
    let gen = `${HEADER(name, def.files)}\n${body}\n\nexport { ${exported.join(', ')} };\n`;
    check(gen.replace(/\nexport \{[^}]*\};\n$/, '\n'), name);
    if (name === 'story-player') {
      gen += `\n/** The rules, player and stylesheet that every exported game is made from (see buildGameHtml). */\nexport const GAME_PARTS = ${JSON.stringify(gameParts())};\n`;
    }
    put(`packages/${name}/src/generated.js`, gen);
    const entry = `packages/${name}/src/index.js`;
    if (!existsSync(join(OUT, entry)) && !existsSync(at(entry))) put(entry, `export * from './generated.js';\n`);
    const entryPath = existsSync(join(OUT, entry)) ? join(OUT, entry) : at(entry);
    put(`packages/${name}/dist/${name}.mjs`, HEADER(name, def.files) + bundle(entryPath, 'esm'));
    put(`packages/${name}/dist/${name}.global.js`, HEADER(name, def.files) + bundle(entryPath, 'iife', def.global));
    put(`packages/${name}/dist/${name}.min.mjs`, HEADER(name, def.files) + bundle(entryPath, 'esm', undefined, true));
    put(`packages/${name}/dist/${name}.min.global.js`, HEADER(name, def.files) + bundle(entryPath, 'iife', def.global, true));
  }
  if (CHECK) {
    const bad = written.filter(p => !existsSync(at(p)) || readFileSync(at(p), 'utf8') !== readFileSync(join(OUT, p), 'utf8'));
    rmSync(OUT, { recursive: true, force: true });
    if (bad.length) {
      console.error('Out of date (run: npm run build):\n  ' + bad.join('\n  '));
      process.exit(1);
    }
    console.log('packages are up to date with the editor sources');
  }
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) generate();
